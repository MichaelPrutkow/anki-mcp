// Writes src/anki_mcp/mathjax_names.py: the macro and environment names that MathJax knows in Anki.
// Anki 25.9 ships MathJax 3.2.2 as tex-chtml-full (every package in AllPackages) without textmacros.
//
//   npm install --prefix /tmp/mj mathjax-full@3.2.2
//   node scripts/mathjax_names.js /tmp/mj/node_modules/mathjax-full > src/anki_mcp/mathjax_names.py
const js = process.argv[2] + "/js";
const { AllPackages } = require(js + "/input/tex/AllPackages.js");
const { ConfigurationHandler } = require(js + "/input/tex/Configuration.js");
const { MapHandler } = require(js + "/input/tex/MapHandler.js");
const version = require(process.argv[2] + "/package.json").version;

const packages = AllPackages.filter((p) => p !== "textmacros");
const macros = new Set();
const environments = new Set();
for (const name of packages) {
  const handler = ConfigurationHandler.get(name).handler;
  for (const [kind, target] of [["macro", macros], ["delimiter", macros], ["environment", environments]]) {
    for (const mapName of handler[kind] || []) {
      const map = MapHandler.getMap(mapName);
      if (map && map.map instanceof Map) {
        for (const key of map.map.keys()) {
          if (kind !== "delimiter") target.add(key);
          else if (key.startsWith("\\")) target.add(key.slice(1));
        }
      }
    }
  }
}
// Characters TeX treats as macros on their own (\, \; \{ ...) are not words and never need checking.
const words = (set) => [...set].filter((n) => /^[a-zA-Z]+\*?$/.test(n)).sort();
const block = (names) => {
  const lines = [];
  let line = "";
  for (const n of names) {
    if (line.length + n.length + 1 > 110) {
      lines.push(line.trim());
      line = "";
    }
    line += " " + n;
  }
  return [...lines, line.trim()].map((l) => "    " + l).join("\n");
};
console.log(`"""Macro and environment names MathJax ${version} knows in Anki (tex-chtml-full without textmacros).

Generated by scripts/mathjax_names.js. Do not edit by hand.
"""

_MACROS = """
${block(words(macros))}
"""

_ENVIRONMENTS = """
${block(words(environments))}
"""

MACROS = frozenset(_MACROS.split())
ENVIRONMENTS = frozenset(_ENVIRONMENTS.split())`);
